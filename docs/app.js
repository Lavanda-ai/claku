// ─── Pairing ───
async function handleGeneratePair() {
  const ownerName = dom.ownerNameInput.value.trim() || 'anonymous';
  
  // Generate 6-digit pairing code
  const code = generatePairingCode();
  state.currentPairingCode = code;
  state.pairingExpiry = nowTs() + 300; // 5 minutes
  
  // Persist to localStorage so it survives page refresh
  localStorage.setItem('claku_pairing_code', code);
  localStorage.setItem('claku_pairing_expiry', state.pairingExpiry);
  
  // Display code to user
  dom.pairingCodeDisplay.textContent = code;
  dom.pairingCodeSection.classList.remove('hidden');
  dom.pairingStatus.textContent = 'Connecting to Waku network...';
  dom.pairingStatus.className = 'pairing-status';
  dom.generatePairBtn.disabled = true;
  
  // Start expiry timer
  updateExpiryTimer();
  
  // Publish pairing request to Waku
  const pairingRequest = {
    type: 'pairing_request',
    pairing_code: code,
    owner_name: ownerName,
    created_at: nowTs(),
    expires_at: state.pairingExpiry,
    msg_id: crypto.randomUUID?.() || '' + Date.now(),
    ts: nowTs()
  };
  
  // Publish to pairing topic
  const ok = await publishTopic(PAIRING_TOPIC, pairingRequest);
  
  if (ok) {
    // Add to activity feed
    addActivity('pairing_request', { code, owner_name: ownerName });
    
    // Instructions for user
    dom.pairingStatus.innerHTML = `Pairing request sent!<br>Code: <strong>${code}</strong><br>Waiting for agent to accept...`;
    dom.pairingStatus.className = 'pairing-status success';
  } else {
    dom.pairingStatus.textContent = 'Failed to send pairing request. Check connection.';
    dom.pairingStatus.className = 'pairing-status error';
    dom.generatePairBtn.disabled = false;
  }
}

// ─── Send Channel Message ───
async function sendChannelMsg() {
  const text = dom.channelMsgInput.value.trim();
  if (!text || !state.currentChannel) return;
  
  // Send command to agent to post the message
  const command = {
    type: 'command',
    command: 'send_channel',
    params: {
      channel: state.currentChannel,
      text: text
    },
    from: 'dashboard',
    to: state.pairedAgentPubkey,
    ts: nowTs(),
    msg_id: 'cmd-' + (crypto.randomUUID?.() || Date.now())
  };
  
  const ok = await publishTopic(`/claku/1/command/${state.pairedAgentPubkey}/proto`, command);
  if (ok) {
    addActivity('system', { text: `Sent message to #${state.currentChannel}` });
  } else {
    addActivity('error', { text: 'Failed to send message' });
  }
  dom.channelMsgInput.value = '';
}

