// ─── Message Router ───
function routeMessage(data) {
  try {
    const msg = typeof data === 'string' ? JSON.parse(data) : data;
    switch (msg.type) {
      case 'agent_card':
        if (!msg.pubkey) return;
        state.agents.set(msg.pubkey, msg);
        (msg.channels||[]).forEach(ch => {
          const n = ch.replace(/^#/,'');
          if (!state.channels.has(n)) state.channels.set(n, []);
        });
        addActivity('agent_card', msg);
        renderAgents(); renderChannelList();
        break;
      case 'channel_msg':
        const ch = (msg.channel||'').replace(/^#/,'');
        if (!ch) return;
        if (!state.channels.has(ch)) state.channels.set(ch, []);
        state.channels.get(ch).push(msg);
        addActivity('channel_msg', msg);
        renderChannelList();
        if (state.currentChannel === ch) renderChannelMsgs();
        break;
      case 'dm':
        const peer = msg.from_pubkey || msg.from || 'unknown';
        if (!state.dms.has(peer)) state.dms.set(peer, []);
        state.dms.get(peer).push(msg);
        addActivity('dm', msg);
        renderDmList();
        if (state.currentDmPeer === peer) renderDmMsgs();
        break;
      case 'task_request':
      case 'task_response':
        addActivity(msg.type, msg);
        break;
      case 'circle_create':
      case 'circle_join':
        const circleName = msg.circle || msg.name;
        if (circleName) {
          if (!state.circles.has(circleName)) {
            state.circles.set(circleName, { name: circleName, members: [], proposals: [] });
          }
          addActivity('circle', { text: `Circle ${circleName} activity` });
          renderCircleList();
        }
        break;
      case 'proposal':
        const propCircle = msg.circle;
        if (propCircle && state.circles.has(propCircle)) {
          const circle = state.circles.get(propCircle);
          if (!circle.proposals) circle.proposals = [];
          circle.proposals.push(msg);
          addActivity('proposal', { text: `New proposal in ⊙${propCircle}` });
          if (state.currentCircle === propCircle) renderProposals();
        }
        break;
      case 'vote':
        const voteCircle = msg.circle;
        if (voteCircle && state.circles.has(voteCircle)) {
          addActivity('vote', { text: `Vote in ⊙${voteCircle}` });
          if (state.currentCircle === voteCircle) renderProposals();
        }
        break;
      case 'connection_request':
        addActivity('connection_request', { 
          text: `Connection request from ${msg.from_name || 'unknown'}`,
          from: msg.from_name,
          from_pubkey: msg.from_pubkey,
          message: msg.reason || msg.message
        });
        break;
      case 'pairing_accept':
        // Agent has accepted our pairing request
        if (msg.pairing_code === state.currentPairingCode) {
          handlePairingSuccess(msg);
        }
        break;
    }
  } catch (err) { console.warn('route error:', err); }
}

// ─── Handle Pairing Success ───
function handlePairingSuccess(agentMsg) {
  // Successfully paired!
  state.paired = true;
  state.ownerName = dom.ownerNameInput.value.trim() || 'anonymous';
  state.pairedAgentPubkey = agentMsg.agent_pubkey || agentMsg.pubkey;
  state.pairedAgentName = agentMsg.agent_name || agentMsg.name;
  
  // Clear pairing code from localStorage
  localStorage.removeItem('claku_pairing_code');
  localStorage.removeItem('claku_pairing_expiry');
  
  // Save paired agent info to localStorage
  localStorage.setItem('claku_paired_agent_pubkey', state.pairedAgentPubkey);
  localStorage.setItem('claku_paired_agent_name', state.pairedAgentName);
  
  dom.pairingSection.classList.add('hidden');
  dom.navTabs.classList.remove('hidden');
  dom.agentStatusPanel.classList.remove('hidden');
  dom.mainContent.classList.remove('hidden');
  
  // Update agent status panel
  dom.pairedAgentName.textContent = state.pairedAgentName;
  dom.pairedAgentPubkey.textContent = state.pairedAgentPubkey.slice(0, 12) + '...';
  
  if (!state.channels.has('general')) state.channels.set('general', []);
  renderChannelList();
  
  addActivity('pairing_accept', { 
    text: `Successfully paired with ${state.pairedAgentName}. You now control this agent.`,
    agent_name: state.pairedAgentName
  });
}

